create schema if not exists extensions;
create extension if not exists btree_gist with schema extensions;

create table if not exists public.courts (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(trim(name)) between 2 and 80),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  court_id bigint not null references public.courts(id) on delete restrict,
  booking_date date not null,
  start_minute integer not null,
  duration_minutes integer not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint bookings_start_in_opening_hours
    check (start_minute >= 480 and start_minute < 1320 and start_minute % 30 = 0),
  constraint bookings_valid_duration
    check (duration_minutes in (60, 90, 120)),
  constraint bookings_end_before_close
    check (start_minute + duration_minutes <= 1320),
  constraint bookings_no_overlapping_times
    exclude using gist (
      court_id with =,
      booking_date with =,
      (int4range(start_minute, start_minute + duration_minutes, '[)')) with &&
    )
);

alter table public.courts enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Authenticated users can view active courts" on public.courts;
create policy "Authenticated users can view active courts"
  on public.courts for select to authenticated
  using (active);

drop policy if exists "Authenticated users can view booked time slots" on public.bookings;
create policy "Authenticated users can view booked time slots"
  on public.bookings for select to authenticated
  using (auth.uid() is not null);

drop policy if exists "Users can create their own future bookings" on public.bookings;
create policy "Users can create their own future bookings"
  on public.bookings for insert to authenticated
  with check (auth.uid() = user_id and booking_date >= current_date);

drop policy if exists "Users can cancel their own bookings" on public.bookings;
create policy "Users can cancel their own bookings"
  on public.bookings for delete to authenticated
  using (auth.uid() = user_id);

revoke all on public.courts from anon;
revoke all on public.bookings from anon;
grant select on public.courts to authenticated;
grant select, insert, delete on public.bookings to authenticated;

